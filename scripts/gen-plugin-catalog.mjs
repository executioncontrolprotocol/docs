#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises"
import { existsSync } from "node:fs"
import { basename, join } from "node:path"
import {
  docsRoot,
  listPluginDirs,
  mdxEscape,
  readJson,
  resolveEcpRoot,
} from "./lib/reference-utils.mjs"

const NPM_SEARCH =
  "https://registry.npmjs.org/-/v1/search?text=keywords:ecosystem:ecp-plugin&size=100"

/**
 * @typedef {{
 *   packageName: string
 *   version: string
 *   installName: string
 *   id: string
 *   summary: string
 *   kind: "extension" | "policy"
 *   description: string
 * }} FirstPartyPlugin
 */

/**
 * @param {string} dir
 * @returns {Promise<FirstPartyPlugin>}
 */
async function loadPlugin(dir) {
  const pkg = /** @type {{ name: string, version?: string, description?: string }} */ (
    await readJson(join(dir, "package.json"))
  )
  const slug = pkg.name.replace(/^@executioncontrolprotocol\/plugin-/, "").replace(/^@executioncontrolprotocol\//, "")
  const srcCandidates = ["src/index.ts", "src/index.tsx", "src/extension.ts", "src/policy.ts"]
  let source = ""
  for (const rel of srcCandidates) {
    const path = join(dir, rel)
    if (existsSync(path)) {
      source = await readFile(path, "utf8")
      break
    }
  }
  const kind = source.includes("definePolicy(") ? "policy" : "extension"
  const defineMatch =
    source.match(/define(?:Extension|Policy)\("([^"]+)",\s*"([^"]+)"\)/) ??
    source.match(/define(?:Extension|Policy)\(\s*\{[\s\S]*?id:\s*"([^"]+)"/)
  let id
  if (defineMatch && defineMatch[2]) {
    id = `${defineMatch[1]}/${defineMatch[2]}`
  } else if (defineMatch) {
    id = defineMatch[1]
  } else {
    id = `@executioncontrolprotocol/${slug}`
  }
  const summary =
    matchQuoted(source, "summary") ?? pkg.description ?? pkg.name
  return {
    packageName: pkg.name,
    version: pkg.version ?? "0.0.0",
    installName: slug,
    id,
    summary,
    kind,
    description: pkg.description ?? summary,
  }
}

/**
 * @param {string} source
 * @param {string} key
 */
function matchQuoted(source, key) {
  const re = new RegExp(`${key}:\\s*"([^"]*)"`)
  const match = source.match(re)
  return match?.[1]
}

/**
 * @returns {Promise<{ packages: { name: string, description?: string, version?: string }[], error?: string, empty: boolean }>}
 */
async function searchThirdParty() {
  try {
    const response = await fetch(NPM_SEARCH, {
      headers: { accept: "application/json" },
    })
    if (!response.ok) {
      return { packages: [], error: `registry.npmjs.org returned ${response.status}`, empty: true }
    }
    const body = /** @type {{ objects?: { package: { name: string, description?: string, version?: string } }[] }} */ (
      await response.json()
    )
    const packages = (body.objects ?? [])
      .map((row) => row.package)
      .filter((pkg) => pkg?.name && !pkg.name.startsWith("@executioncontrolprotocol/"))
    return { packages, empty: packages.length === 0 }
  } catch (err) {
    return {
      packages: [],
      error: err instanceof Error ? err.message : String(err),
      empty: true,
    }
  }
}

/**
 * @param {string} ecpRoot
 */
export async function generatePluginCatalog(ecpRoot) {
  const dirs = await listPluginDirs(ecpRoot)
  const firstParty = []
  for (const dir of dirs) {
    firstParty.push(await loadPlugin(dir))
  }
  firstParty.sort((a, b) => a.packageName.localeCompare(b.packageName))
  const third = await searchThirdParty()

  const rows = firstParty.map((plugin) => {
    return [
      `## \`${plugin.packageName}\``,
      "",
      mdxEscape(plugin.summary),
      "",
      `| Field | Value |`,
      `| --- | --- |`,
      `| Kind | ${plugin.kind} |`,
      `| Id | \`${plugin.id}\` |`,
      `| Version (monorepo) | \`${plugin.version}\` |`,
      `| Install | \`ecp plugins install ${plugin.installName}\` |`,
      "",
    ].join("\n")
  })

  const thirdSection = third.error
    ? `Could not query \`registry.npmjs.org\` (${mdxEscape(third.error)}). First-party list is from the ECP checkout, not npm.`
    : third.empty
      ? "No third-party packages with keyword `ecosystem:ecp-plugin` are on the npm registry yet. First-party plugins are listed from the monorepo because they are not published."
      : [
          "| Package | Version | Description |",
          "| --- | --- | --- |",
          ...third.packages.map(
            (pkg) =>
              `| \`${pkg.name}\` | \`${pkg.version ?? ""}\` | ${mdxEscape(pkg.description ?? "")} |`
          ),
        ].join("\n")

  const body = [
    "---",
    'title: "Plugins"',
    'description: "Generated plugin catalogue for ECP (Execution Control Protocol)."',
    "---",
    "",
    "{/* Generated by scripts/gen-plugin-catalog.mjs. Do not edit by hand. */}",
    "",
    "# Plugins",
    "",
    "First-party plugins are listed from `plugins/plugin-*` in the ECP checkout. They are not installed from `@next` (unpublished). Third-party plugins are whatever `registry.npmjs.org` returns for keyword `ecosystem:ecp-plugin`.",
    "",
    "Install with `ecp plugins install <name>`. Package name is `plugin-` plus the extension or policy name; the protocol id is unchanged.",
    "",
    "```bash",
    "ecp plugins install jsonata",
    "```",
    "",
    "## First-party",
    "",
    ...rows,
    "## Third-party",
    "",
    thirdSection,
    "",
    "## Next steps",
    "",
    "- [Writing a plugin](/guides/writing-a-plugin)",
    "- [CLI](/reference/cli)",
    "",
  ].join("\n")

  const out = join(docsRoot, "reference", "plugins.mdx")
  await writeFile(out, body, "utf8")
  return out
}

if (process.argv[1]?.endsWith("gen-plugin-catalog.mjs")) {
  const out = await generatePluginCatalog(resolveEcpRoot())
  console.log(`wrote ${out}`)
}
